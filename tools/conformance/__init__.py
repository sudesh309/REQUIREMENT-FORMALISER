"""Spec-conformance metrics, a regression baseline and per-phase targets.

Each module in ``tools/conformance/metrics/`` defines ``collect()`` returning a
list of metric dicts::

    {"name": "parse.library.files_ok", "value": 0.97,
     "better": "higher",            # "higher", "lower" or "info" (never a regression)
     "detail": [...]}               # optional: failures, for the report

``run()`` gathers them. ``regressions()`` compares a run with ``baseline.json``
(a metric that got worse, or disappeared, is a regression). ``unmet_targets()``
checks ``targets.json`` for the phases named. Streams run in parallel, so a
gate names every phase it needs (a milestone gate names all of its phases).

Command line (also used by ``python -m tools.gate``)::

    python -m tools.conformance                     # report, compare with baseline
    python -m tools.conformance --phase 1 --phase 2a   # ... and check those phases' targets
    python -m tools.conformance --update-baseline   # accept the current values
    python -m tools.conformance --markdown docs/CONFORMANCE_STATUS.md

Parallel work streams add metric modules but never edit ``baseline.json``; the
baseline is updated when a stream is merged.
"""
from __future__ import annotations

import importlib
import json
import pkgutil
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASELINE = HERE / "baseline.json"
TARGETS = HERE / "targets.json"
EPS = 1e-9


def run() -> dict[str, dict]:
    """Collect every metric; a failing collector is reported as a metric of its own."""
    from . import metrics
    out: dict[str, dict] = {}
    for mod in sorted(m.name for m in pkgutil.iter_modules(metrics.__path__)):
        started = time.perf_counter()
        try:
            module = importlib.import_module(f"{metrics.__name__}.{mod}")
            results = module.collect()
        except Exception as exc:  # noqa: BLE001 - a broken collector must not hide the others
            out[f"{mod}.collector_ok"] = {"name": f"{mod}.collector_ok", "value": 0.0,
                                          "better": "higher", "detail": [repr(exc)]}
            continue
        out[f"{mod}.collector_ok"] = {"name": f"{mod}.collector_ok", "value": 1.0, "better": "higher"}
        out[f"{mod}.seconds"] = {"name": f"{mod}.seconds", "better": "info",
                                 "value": round(time.perf_counter() - started, 2)}
        for m in results:
            out[m["name"]] = m
    return out


def load_baseline() -> dict[str, dict]:
    return json.loads(BASELINE.read_text()) if BASELINE.exists() else {}


def save_baseline(report: dict[str, dict]) -> None:
    data = {k: {"value": v["value"], "better": v.get("better", "higher")}
            for k, v in sorted(report.items()) if v.get("better") != "info"}
    BASELINE.write_text(json.dumps(data, indent=2) + "\n")


def regressions(report: dict[str, dict], baseline: dict[str, dict]) -> list[str]:
    problems = []
    for name, base in baseline.items():
        better = base.get("better", "higher")
        if better == "info":
            continue
        if name not in report:
            problems.append(f"{name}: metric disappeared (was {base['value']})")
            continue
        now, was = report[name]["value"], base["value"]
        if (better == "higher" and now < was - EPS) or (better == "lower" and now > was + EPS):
            problems.append(f"{name}: {was} -> {now} ({better} is better)")
    return problems


def load_targets() -> dict[str, dict]:
    return json.loads(TARGETS.read_text()) if TARGETS.exists() else {}


def unmet_targets(report: dict[str, dict], phases: list[str]) -> list[str]:
    """Targets of the given phases that the report does not meet."""
    targets = load_targets()
    known = [p for p in targets if not p.startswith("_")]
    unknown = [p for p in phases if p not in known]
    if unknown:
        raise KeyError(f"unknown phase(s) {unknown}; known: {known}")
    problems = []
    for p in phases:
        for name, bound in targets[p].items():
            if name.startswith("_"):
                continue
            value = report.get(name, {}).get("value")
            if value is None:
                problems.append(f"[phase {p}] {name}: not measured")
            elif "min" in bound and value < bound["min"] - EPS:
                problems.append(f"[phase {p}] {name}: {value} < {bound['min']}")
            elif "max" in bound and value > bound["max"] + EPS:
                problems.append(f"[phase {p}] {name}: {value} > {bound['max']}")
    return problems


def markdown(report: dict[str, dict]) -> str:
    """A status page: every metric, then each phase's targets and whether they are met."""
    targets = load_targets()
    lines = ["# Conformance status", "",
             "Generated by `python -m tools.conformance --markdown`. Do not edit by hand.", "",
             "## Metrics", "", "| Metric | Value | Better |", "|---|---|---|"]
    for name in sorted(report):
        m = report[name]
        lines.append(f"| `{name}` | {m['value']} | {m.get('better', 'higher')} |")
    for phase, items in targets.items():
        if phase.startswith("_"):
            continue
        lines += ["", f"## Phase {phase} targets", "", "| Metric | Target | Now | Met |",
                  "|---|---|---|---|"]
        for name, bound in items.items():
            if name.startswith("_"):
                continue
            target = (f">= {bound['min']}" if "min" in bound else f"<= {bound['max']}")
            now = report.get(name, {}).get("value")
            met = now is not None and not (("min" in bound and now < bound["min"] - EPS)
                                           or ("max" in bound and now > bound["max"] + EPS))
            lines.append(f"| `{name}` | {target} | {'—' if now is None else now} | "
                         f"{'yes' if met else 'no'} |")
    return "\n".join(lines) + "\n"
